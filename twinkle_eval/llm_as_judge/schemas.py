"""
Pydantic schemas for LLM-as-Judge evaluations.

This module defines the data structures used throughout the LLM-as-Judge framework.
"""

from typing import Any, Dict, List, Optional, Union
from pydantic import BaseModel, Field


class TestCase(BaseModel):
    """
    Represents a single test case for evaluation.

    Attributes:
        input: The input/question provided to the LLM
        actual_output: The actual output generated by the LLM
        expected_output: Optional expected/reference output
        retrieval_context: Optional context used for generation (for RAG systems)
        metadata: Additional metadata about the test case
    """
    input: str = Field(..., description="The input question or prompt")
    actual_output: str = Field(..., description="The LLM's generated output")
    expected_output: Optional[str] = Field(None, description="Expected or reference output")
    retrieval_context: Optional[List[str]] = Field(None, description="Retrieved context for RAG")
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Additional metadata")


class MetricResult(BaseModel):
    """
    Result of a metric evaluation.

    Attributes:
        score: Numeric score (typically 0-1 or 0-10 depending on metric)
        success: Whether the metric passed (score >= threshold)
        reason: Explanation for the score
        metric_name: Name of the metric that produced this result
        metadata: Additional information from the evaluation
    """
    score: float = Field(..., description="Numeric score from the evaluation")
    success: bool = Field(..., description="Whether the metric passed")
    reason: str = Field(..., description="Explanation for the score")
    metric_name: str = Field(..., description="Name of the metric")
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Additional metadata")


class ReasonScore(BaseModel):
    """Simple schema for reason and score output."""
    reason: str = Field(..., description="Reasoning for the score")
    score: float = Field(..., description="Numeric score")


class Verdict(BaseModel):
    """Verdict for a single claim or statement."""
    verdict: str = Field(..., description="The verdict (e.g., 'yes', 'no', 'idk')")
    reason: Optional[str] = Field(None, description="Reasoning for the verdict")


class Claims(BaseModel):
    """List of claims extracted from text."""
    claims: List[str] = Field(default_factory=list, description="List of extracted claims")


class Truths(BaseModel):
    """List of truths extracted from context."""
    truths: List[str] = Field(default_factory=list, description="List of extracted truths")


class Verdicts(BaseModel):
    """List of verdicts for multiple claims."""
    verdicts: List[Verdict] = Field(default_factory=list, description="List of verdicts")


class EvaluationSteps(BaseModel):
    """Steps for performing an evaluation."""
    steps: List[str] = Field(default_factory=list, description="Evaluation steps")


class Rubric(BaseModel):
    """
    Rubric for score interpretation in G-Eval.

    Attributes:
        score_range: Tuple of (min_score, max_score)
        description: Description of what this score range means
    """
    score_range: tuple[int, int] = Field(..., description="Score range (min, max)")
    description: str = Field(..., description="Description of this score range")

    class Config:
        frozen = True  # Make it immutable
